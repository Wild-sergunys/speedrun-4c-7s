#define MENU                                         \
    "\nВыберите:                                  \n" \
    " [1] - Загрузить данные и выполнить анализ;  \n"  \
    " [2] - Показать формат данных;               \n"   \
    " [3] - Запустить тесты;                      \n"    \
    " [4] - Завершить программу.                  \n"

enum menu_choice {
  MENU_ANALYSIS = 1,
  MENU_HELP,
  MENU_TESTS,
  MENU_EXIT
};

int main() {
  SetConsoleCP(1251);
  SetConsoleOutputCP(1251);
  setlocale(LC_ALL, "Russian");
  std::cout << GREETING << TASK;

  for (;;) {
    std::cout << MENU;
    int choice = get_int();

    switch (choice) {
    case MENU_ANALYSIS:
      run_analysis();
      break;
    case MENU_HELP:
      show_help();
      break;
    case MENU_TESTS:
      run_tests();
      break;
    case MENU_EXIT:
      std::cout << "Программа завершена.\n";
      return 0;
    default:
      std::cout << "Ошибка: выберите 1, 2, 3 или 4.\n";
      break;
    }
  }
}